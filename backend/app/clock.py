"""**오늘이 언제인지는 기계가 아니라 시장이 정한다.**

파이썬의 `date.today()` 는 그 코드가 도는 **기계의 시간대**를 쓴다. 개발 PC 는 KST 고
배포 서버는 UTC 다. 그래서 같은 코드가 두 곳에서 다른 날짜를 낸다 — 한국시간 자정부터
아침 9시까지 **서버만 하루 뒤처진다.**

실제로 어긋나 있었다(2026-09-06 확인). 서버는 `2026-09-05`, 사용자 화면은 `2026-09-06`.
그 시간대에 걸린 것들:

- 다가오는 일정의 `D-n` 이 전부 하루씩 밀린다. 어제 일정이 "오늘"로 남는다.
- DART 공시 조회의 끝 날짜가 어제가 되어 **아침에 올라온 공시가 안 보인다.**
- 사업보고서·분기보고서의 "지금 나와 있을 만한 기간" 판단이 연말에 한 해를 건너뛴다.

`routers/events.py` 에는 *"서버와 브라우저의 오늘이 어긋나지 않도록 여기서 낸다 —
시간대가 다르면 하루 어긋난다"* 고 적혀 있었는데, 정작 `date.today()` 를 쓰고 있었다.
막으려던 바로 그것을 하고 있었던 셈이다.

**그래서 시간대를 코드에 못 박는다.** 이 프로젝트가 다루는 날짜 — 거래일, 공시일,
보고서 기간 — 는 전부 한국 기준이거나(KRX·DART) 시장이 스스로 날짜를 붙여 보내 준다
(토스·SEC). 기계의 시간대가 끼어들 자리는 없다.

미국 시간대(ET)를 여기 두지 않은 이유: 미국 장 상태는 토스가 세션으로 알려 주고,
SEC 공시는 응답에 날짜가 붙어 온다. 우리가 ET 로 "오늘"을 계산하는 곳이 없다.
필요해지면 그때 `zoneinfo` 로 넣는다 — 서머타임 때문에 고정 오프셋으로는 안 된다.
"""

from __future__ import annotations

from datetime import date, datetime, timedelta, timezone

# 한국 표준시. 서머타임이 없어 고정 오프셋으로 정확하다.
KST = timezone(timedelta(hours=9))


def now_kst() -> datetime:
    """지금(한국시간). 시간대가 붙어 있는 값이다."""
    return datetime.now(KST)


def today_kst() -> date:
    """오늘(한국 기준). `date.today()` 대신 이것을 쓴다.

    거래일·공시일·보고서 기간처럼 **한국 달력으로 세는 날짜**는 전부 여기서 가져온다.
    """
    return now_kst().date()
