"""도식으로 그릴 **구조** — 국내(사업보고서)와 미국(10-K)이 함께 쓴다.

## 왜 이 파일이 따로 있나

두 시장의 분석 스키마는 문서가 달라 각자의 파일에 있다. 그런데 **카드는 한 장이다** —
`DecoderCard` 하나를 둘이 나눠 쓰고, 그래서 "두 시장의 카드가 같은 모양이어야 한다"가
v2 때부터의 약속이었다. 도식용 필드를 각 파일에 따로 적으면 그 약속이 조용히 깨진다.
설명 한 글자가 달라지면 두 시장의 그림이 서로 다른 것을 그리게 된다.

## 여기에도 수치 필드는 없다 (절대 규칙 3)

이 파일이 받는 것은 **구조**다. 누가 누구에게 무엇을 주는가, 위험이 어떤 성격인가.
"매출의 몇 %" 같은 것은 하나도 없다 — 그런 숫자는 재무표에서 우리가 직접 계산한다.

구조와 수치의 경계가 헷갈릴 수 있어 기준을 적어 둔다. **세면 답이 나오는 것은 수치,
세어도 답이 안 나오는 것은 구조다.** "고객이 몇 곳인가"는 수치라 받지 않고,
"누가 돈을 내는가"는 구조라 받는다.

## 없으면 없다고 둔다

보고서에 근거가 없으면 빈 목록으로 돌아온다. 화면은 그때 그 도식을 아예 그리지 않는다.
빈 상자에 그럴듯한 말을 채워 넣는 것보다 낫다 — 도식은 글보다 더 사실처럼 보이기 때문에
지어낸 것이 섞이면 더 위험하다.
"""

from __future__ import annotations

from typing import Literal, get_args

from pydantic import BaseModel, Field

# 위험을 지도 위에 놓으려면 **축이 있어야 한다.** 자유 문자열로 받으면 회사마다 다른
# 말이 나와서 축이 서지 않는다("공급망 리스크" / "부품 조달" / "협력사 의존"이 다 따로
# 칸을 차지한다). 목록으로 못 박고, 어디에도 안 맞는 것은 '기타'로 떨어지게 둔다.
RiskCategory = Literal[
    "규제·정책",
    "경쟁",
    "공급망",
    "고객 집중",
    "수요·가격",
    "기술 변화",
    "재무·환율",
    "소송·제재",
    "기타",
]
# '수요·가격' 은 첫 시험(삼성전자) 뒤에 보탠 것이다. "메모리 가격 급등에 따른 세트 수요
# 위축"이 갈 곳이 없어 '기타' 로 떨어졌는데, 제조업·시황 산업에서 가장 흔한 위험을
# 잡동사니 칸에 두면 지도의 한 칸이 통째로 의미를 잃는다.

# 지도의 다른 축. **심각도가 아니라 시점이다.** 심각도는 판단이라 LLM 에게 시키면
# 투자 의견에 가까워진다(프롬프트 규칙 3 이 금지하는 것). 시점은 보고서에 적혀 있다 —
# 이미 소송이 걸렸는지, 법이 통과됐는데 시행 전인지, 아직 말뿐인지.
RiskTiming = Literal["이미 진행 중", "다가오는", "잠재적"]

RISK_CATEGORIES: tuple[str, ...] = get_args(RiskCategory)
RISK_TIMINGS: tuple[str, ...] = get_args(RiskTiming)


class RevenueSource(BaseModel):
    """돈을 내는 쪽 하나."""

    who: str = Field(
        description="누가 돈을 내는가. 10자 안팎의 짧은 말. 예: '스마트폰 제조사'"
    )
    pays_for: str = Field(
        description="무엇에 대해 내는가. 12자 안팎. 예: '메모리 반도체'"
    )


class MoneyFlow(BaseModel):
    """돈이 어디서 들어와 어디로 나가는지. **흐름도의 재료다.**

    세 칸으로 그린다: `inputs` → `engine` → `revenue_sources`.
    한 문장 요약(`one_liner`)으로는 상자를 자를 수 없어서 항목으로 따로 받는다.
    """

    inputs: list[str] = Field(
        description=(
            "이 회사가 돈을 주고 사오거나 들이는 것 2~4개. 각 10자 안팎. "
            "예: '웨이퍼', '노광장비', '설계 인력'. 보고서에 없으면 빈 목록"
        )
    )
    engine: str = Field(
        description=(
            "사 온 것을 무엇으로 바꿔 값을 붙이는가. 한 줄 25자 안팎. "
            "예: '나노 공정으로 칩을 찍어낸다'"
        )
    )
    revenue_sources: list[RevenueSource] = Field(
        description=(
            "돈을 내는 쪽 2~5개. 회사에 중요한 순서로. "
            "보고서가 고객을 밝히지 않으면 빈 목록"
        )
    )


# 두 시장의 시스템 프롬프트 끝에 **그대로 같이** 붙는다. 한쪽만 고치면 두 카드가
# 다른 것을 그리기 시작하므로 문장을 여기 한 곳에만 둔다.
DIAGRAM_RULES = """\

`money_flow`·`competitors`·위험의 `category`·`timing` 은 **그림으로 그려지는 항목**입니다.
글이 아니라 상자와 화살표가 되므로 다음을 지키십시오.

9. **`money_flow` 는 돈의 흐름도가 됩니다.** 세 칸으로 그려집니다.
   - `inputs`: 회사가 **돈을 주고 사오는 것**. 원재료·부품·장비·저작권·인력처럼
     회사 바깥에서 들여오는 것입니다. 회사가 파는 것을 여기 적지 마십시오.
   - `engine`: 그것을 **무엇으로 바꾸는가**. 이 회사가 값을 붙이는 지점 한 줄입니다.
   - `revenue_sources`: **누가 돈을 내는가**. 최종 소비자인지, 기업인지, 광고주인지,
     정부인지를 밝히십시오. 제품 이름이 아니라 **돈을 내는 주체**를 적습니다.
     좋은 예: who='통신사', pays_for='기지국 장비'.
     나쁜 예: who='5G 사업부', pays_for='매출' — 둘 다 회사 안쪽이라 흐름이 되지 않습니다.
   - 보고서에 근거가 없는 칸은 **빈 목록으로 두십시오.** 그러면 그 도식을 그리지
     않습니다. 지어내면 그림이 되어 글보다 더 사실처럼 보입니다.

10. **`competitors` 는 보고서가 이름을 댄 경쟁사만** 적으십시오. 업계 상식으로 아는
    회사를 보태지 마십시오. 이름이 없으면 빈 목록입니다.

11. **위험마다 `category` 와 `timing` 을 붙이십시오.** 위험 지도의 두 축입니다.
    - `category` 는 주어진 목록에서 고릅니다. 어디에도 맞지 않으면 '기타'입니다.
    - `timing` 은 **심각도가 아니라 시점**입니다. 보고서에 적힌 사실로 고르십시오.
      '이미 진행 중' = 소송이 걸려 있거나 제재를 받았거나 이미 실적에 반영됨.
      '다가오는' = 법·계약·만기처럼 시점이 정해진 것.
      '잠재적' = 조건이 맞으면 일어날 수 있다고만 적힌 것.
      얼마나 나쁜지는 판단이므로 고르지 마십시오.
"""
